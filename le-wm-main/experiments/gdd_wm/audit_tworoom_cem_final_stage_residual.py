"""Audit a residual only on the final proposal set of an online CEM run.

The CEM trajectory panel contains several proposal distributions generated by
successive frozen-model updates.  A residual applied before the last update
changes the distribution that produced the later candidates, so a residual
trained on the pooled trajectory is not a clean intervention.  This audit
uses only one predeclared iteration (normally the final one): the first
``n_steps-1`` CEM updates remain frozen-base, and the residual is evaluated
only on the final candidate set.  It therefore tests a decision-aligned,
feedback-safe intervention before wiring the gate into live runtime.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

if __package__ in (None, ""):
    _PROJECT_ROOT = Path(__file__).resolve().parents[2]
    if str(_PROJECT_ROOT) not in sys.path:
        sys.path.insert(0, str(_PROJECT_ROOT))

import numpy as np

from experiments.gdd_wm.audit_runtime_base_residual import _apply_trust_region
from experiments.gdd_wm.audit_train_only_teacher_capacity import (
    _bootstrap,
    _feature_vector,
    _macro_mean_regret,
    _macro_root_regrets,
    _fit_linear_residual_models,
    _load,
)
from experiments.gdd_wm.build_train_only_readout_teacher_package import (
    _action_summary,
    _feature_key,
    _predict,
)


def _load_panel(dataset: Path, arrays_path: Path, stage: int):
    metadata, source_rows = _load(dataset)
    arrays = np.load(arrays_path, allow_pickle=False)
    rows: list[dict[str, Any]] = []
    for row in source_rows:
        if int(row.get("cem_iteration", -1)) != int(stage):
            continue
        # The direct panel stores ``arrays.npz::predicted::...``.  Do not
        # strip the ``predicted::`` namespace: it is part of the NPZ key.
        ref = str(row["predicted_latent_ref"])
        key = ref.split("arrays.npz::", 1)[-1] if "arrays.npz::" in ref else _feature_key(row)
        if key not in arrays.files:
            raise ValueError(f"missing predicted latent array {key}")
        current = dict(row)
        current["_predicted"] = np.asarray(arrays[key], dtype=np.float64)
        rows.append(current)
    if not rows:
        raise ValueError(f"no rows found for cem_iteration={stage}")
    roots = {str(row["instance_id"]) for row in rows}
    if any(sum(str(row["instance_id"]) == root for row in rows) < 2 for root in roots):
        raise ValueError("each final-stage root must contain multiple candidates")
    return metadata, rows


def _metrics(
    prediction: np.ndarray,
    target: np.ndarray,
    roots: np.ndarray,
    mask: np.ndarray,
) -> dict[str, Any]:
    root_regrets = _macro_root_regrets(
        prediction, target, roots.tolist(), roots.tolist(), mask, 1.0e-3
    )
    values = np.asarray(list(root_regrets.values()), dtype=np.float64)
    return {
        "root_count": int(len(values)),
        "mean_regret": _bootstrap(values, np.random.default_rng(20261016), 4000),
        "root_regrets": root_regrets,
    }


def run(
    *, dataset: Path, arrays: Path, output: Path, stage: int,
    seed: int = 20261016, draws: int = 4000,
    target_mode: str = "root_centered", goal_conditioning: str = "latent_relative",
    correction_mode: str = "latent_only", success_penalty: float = 0.0,
) -> dict[str, Any]:
    if success_penalty < 0.0:
        raise ValueError("success_penalty must be nonnegative")
    metadata, rows = _load_panel(dataset, arrays, stage)
    features: list[np.ndarray] = []
    action_features: list[np.ndarray] = []
    targets: list[float] = []
    base_costs: list[float] = []
    roots: list[str] = []
    splits: list[str] = []
    for row in rows:
        predicted = np.asarray(row["_predicted"], dtype=np.float64)
        goal = np.asarray(row["goal_latent_model"], dtype=np.float64)
        features.append(_feature_vector(row, predicted, "raw", goal_conditioning))
        action_features.append(_action_summary(row["action_sequence"]))
        # The deployment consequence is binary success, while the historical
        # residual was trained only on continuous task cost.  This optional,
        # frozen penalty lets calibration test whether a successful candidate
        # should receive a direct margin without consulting outcome roots.
        targets.append(
            float(row["real_task_cost"])
            + float(success_penalty) * (1.0 - float(bool(row["real_success"])))
        )
        base_costs.append(float(np.square(predicted - goal).sum()))
        roots.append(str(row["instance_id"]))
        splits.append(str(row["split"]))
    x = np.asarray(features, dtype=np.float64)
    action_x = np.asarray(action_features, dtype=np.float64)
    y = np.asarray(targets, dtype=np.float64)
    base_cost = np.asarray(base_costs, dtype=np.float64)
    root_array = np.asarray(roots, dtype=object)
    train_mask = np.asarray([item == "train" for item in splits])
    calibration_mask = np.asarray([item == "calibration" for item in splits])
    outcome_mask = np.asarray([item == "outcome" for item in splits])
    train_target = y[train_mask] - base_cost[train_mask]
    if target_mode == "root_centered":
        train_roots = root_array[train_mask]
        for root in np.unique(train_roots):
            local = train_roots == root
            train_target[local] -= np.mean(train_target[local])
    elif target_mode != "absolute":
        raise ValueError(f"unsupported target mode: {target_mode!r}")
    if correction_mode not in ("latent_only", "full"):
        raise ValueError(f"unsupported correction mode: {correction_mode!r}")

    base_calibration = _macro_mean_regret(
        base_cost, y, root_array.tolist(), root_array.tolist(), calibration_mask, 1.0e-3
    )
    base_outcome = _metrics(base_cost, y, root_array, outcome_mask)
    candidate_specs: list[dict[str, Any]] = []
    candidate_predictions: dict[str, np.ndarray] = {}
    correction_grid = (0.0, 0.125, 0.25, 0.5, 0.75, 1.0)
    rank_grid = (0.25, 0.5, 0.75, 1.0)
    alpha_grid = (1.0e-2, 1.0e-1, 1.0, 1.0e1, 1.0e2, 1.0e3)
    for alpha in alpha_grid:
        action_fit, residual_fit = _fit_linear_residual_models(
            x, action_x, train_target, train_mask, alpha
        )
        latent_prediction = _predict(x, residual_fit)
        correction_prediction = (
            _predict(action_x, action_fit) + latent_prediction
            if correction_mode == "full" else latent_prediction
        )
        for multiplier in correction_grid:
            for quantile in rank_grid:
                candidate_id = f"alpha={alpha:g};multiplier={multiplier:g};base_rank_quantile={quantile:g}"
                prediction = _apply_trust_region(
                    base_cost, correction_prediction, root_array,
                    multiplier, quantile,
                )
                calibration_regrets = _macro_root_regrets(
                    prediction, y, root_array.tolist(), root_array.tolist(), calibration_mask, 1.0e-3
                )
                base_regrets = _macro_root_regrets(
                    base_cost, y, root_array.tolist(), root_array.tolist(), calibration_mask, 1.0e-3
                )
                common = sorted(set(calibration_regrets) & set(base_regrets))
                delta = np.asarray(
                    [calibration_regrets[root] - base_regrets[root] for root in common],
                    dtype=np.float64,
                )
                interval = _bootstrap(delta, np.random.default_rng(seed + 7), draws)
                candidate_specs.append({
                    "candidate_id": candidate_id,
                    "alpha": float(alpha),
                    "correction_multiplier": float(multiplier),
                    "base_rank_quantile": float(quantile),
                    "calibration_mean_regret": float(np.mean(list(calibration_regrets.values()))),
                    "calibration_delta_ci95": interval["ci95"],
                    "calibration_gate_pass": bool(interval["ci95"][1] < 0.0),
                })
                candidate_predictions[candidate_id] = prediction
    safe = [item for item in candidate_specs if item["calibration_gate_pass"]]
    selected = min(
        safe or candidate_specs,
        key=lambda item: (
            item["calibration_mean_regret"],
            item["alpha"],
            -item["correction_multiplier"],
            item["base_rank_quantile"],
        ),
    )
    selected_id = str(selected["candidate_id"])
    selected_prediction = candidate_predictions[selected_id]
    selected_calibration = _macro_root_regrets(
        selected_prediction, y, root_array.tolist(), root_array.tolist(), calibration_mask, 1.0e-3
    )
    base_calibration_roots = _macro_root_regrets(
        base_cost, y, root_array.tolist(), root_array.tolist(), calibration_mask, 1.0e-3
    )
    calibration_delta = np.asarray(
        [selected_calibration[root] - base_calibration_roots[root] for root in sorted(base_calibration_roots)],
        dtype=np.float64,
    )
    gate_enabled = bool(selected["calibration_gate_pass"])
    output.mkdir(parents=True, exist_ok=True)
    readout_path = output / "final_stage_residual_readout.npz"
    # Refit exactly the selected alpha for the deployable artifact.
    action_fit, residual_fit = _fit_linear_residual_models(
        x, action_x, train_target, train_mask, float(selected["alpha"])
    )
    np.savez_compressed(
        readout_path,
        action_coefficient=np.asarray(action_fit["coefficients"], dtype=np.float32),
        action_mean=np.asarray(action_fit["mean"], dtype=np.float32),
        action_scale=np.asarray(action_fit["scale"], dtype=np.float32),
        residual_coefficient=np.asarray(residual_fit["coefficients"], dtype=np.float32),
        residual_mean=np.asarray(residual_fit["mean"], dtype=np.float32),
        residual_scale=np.asarray(residual_fit["scale"], dtype=np.float32),
        gate_enabled=np.asarray([int(gate_enabled)], dtype=np.int8),
        base_cost_correction=np.asarray([1], dtype=np.int8),
        action_correction_enabled=np.asarray([int(correction_mode == "full")], dtype=np.int8),
        selected_alpha=np.asarray([float(selected["alpha"])], dtype=np.float64),
        correction_multiplier=np.asarray([float(selected["correction_multiplier"])], dtype=np.float64),
        base_rank_quantile=np.asarray([float(selected["base_rank_quantile"])], dtype=np.float64),
        residual_start_iteration=np.asarray([int(stage)], dtype=np.int64),
        feature_family=np.asarray(["source_delta_action"]),
        action_frame=np.asarray(["raw"]),
        goal_conditioning=np.asarray([goal_conditioning]),
        target_mode=np.asarray([target_mode]),
        success_penalty=np.asarray([float(success_penalty)], dtype=np.float64),
    )
    selected_outcome = _metrics(selected_prediction, y, root_array, outcome_mask)
    report = {
        "schema": "gdd_wm_tworoom_cem_final_stage_residual.v0.1",
        "status": "completed_offline_stage_aligned_audit",
        "protocol": {
            "dataset": str(dataset.resolve()),
            "fit_split": "train roots, final CEM iteration only",
            "selection_split": "calibration roots, final CEM iteration only",
            "evaluation_split": "outcome roots, final CEM iteration only",
            "cem_iteration": int(stage),
            "feedback_safe_deployment": "residual disabled before final iteration",
            "base_cost": "frozen_lewm_terminal_mse",
            "target": (
                "real_task_cost_plus_success_penalty_minus_frozen_base_cost"
                if success_penalty > 0.0 else "real_task_cost_minus_frozen_base_cost"
            ),
            "success_penalty": float(success_penalty),
            "goal_conditioning": goal_conditioning,
            "correction_mode": correction_mode,
            "outcome_used_for_selection": False,
            "gate_rule": "calibration root-macro paired regret CI95 upper bound < 0",
        },
        "selection": {
            "selected": selected,
            "candidate_count": len(candidate_specs),
            "calibration_safe_candidate_count": len(safe),
            "base_calibration_mean_regret": float(base_calibration),
            "selected_calibration_mean_regret": float(np.mean(list(selected_calibration.values()))),
            "selected_minus_base_calibration_delta": _bootstrap(
                calibration_delta, np.random.default_rng(seed + 8), draws
            ),
            "gate_enabled": gate_enabled,
            "fallback": not gate_enabled,
        },
        "metrics": {
            "base_outcome": base_outcome,
            "selected_outcome": selected_outcome,
            "selected_outcome_vs_base": _bootstrap(
                np.asarray([
                    selected_outcome["root_regrets"][root] - base_outcome["root_regrets"][root]
                    for root in sorted(base_outcome["root_regrets"])
                ], dtype=np.float64),
                np.random.default_rng(seed + 9), draws,
            ),
        },
        "runtime_readout_artifact": str(readout_path.resolve()),
        "claim_boundary": (
            "final-CEM-stage train-only residual diagnostic; no live planning claim "
            "until runtime iteration gate and fresh paired outcome"
        ),
    }
    (output / "final_stage_residual_audit.json").write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(json.dumps({
        "selection": report["selection"],
        "metrics": report["metrics"],
        "runtime_readout_artifact": report["runtime_readout_artifact"],
    }, indent=2, sort_keys=True))
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--candidate-dataset", type=Path, required=True)
    parser.add_argument("--arrays", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--stage", type=int, default=7)
    parser.add_argument("--seed", type=int, default=20261090)
    parser.add_argument("--draws", type=int, default=4000)
    parser.add_argument("--target-mode", choices=("absolute", "root_centered"), default="root_centered")
    parser.add_argument("--goal-conditioning", choices=("none", "latent_relative"), default="latent_relative")
    parser.add_argument("--correction-mode", choices=("latent_only", "full"), default="latent_only")
    parser.add_argument(
        "--success-penalty", type=float, default=0.0,
        help="fixed train/calibration target penalty for unsuccessful candidates; outcome never selects it",
    )
    args = parser.parse_args()
    run(
        dataset=args.candidate_dataset,
        arrays=args.arrays,
        output=args.output,
        stage=args.stage,
        seed=args.seed,
        draws=args.draws,
        target_mode=args.target_mode,
        goal_conditioning=args.goal_conditioning,
        correction_mode=args.correction_mode,
        success_penalty=args.success_penalty,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
