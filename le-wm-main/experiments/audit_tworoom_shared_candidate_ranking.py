"""Shared-candidate RGB ranking audit for the frozen TwoRoom LeWM.

Each root uses the same fixed macro-action bank for the frozen RGB model and
for privileged offline labels generated by replaying every candidate from the
same environment seed. The simulator is used only to create held-out labels;
it is never passed to the model's ranking function.
"""

from __future__ import annotations

