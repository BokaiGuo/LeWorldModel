from experiments.run_live_tworoom_planning import TwoRoomGoalAliasWrapper, _image_transform, _load_action_stats


def _directions() -> list[tuple[float, float]]:
    values = [(0.0, 0.0)]
    for magnitude in (0.25, 0.50, 0.75):
        values.extend([
            (magnitude, 0.0), (-magnitude, 0.0),
            (0.0, magnitude), (0.0, -magnitude),
        ])
    values.extend([(0.5, 0.5), (0.5, -0.5), (-0.5, 0.5), (-0.5, -0.5)])
    return values


def _candidate_bank(mean: np.ndarray, std: np.ndarray, horizon: int = 5, action_block: int = 5):
    raw = _directions()
    normalized = []
    for dx, dy in raw:
        frame = np.asarray([dx, dy], dtype=np.float32)
        block = np.tile(frame, (action_block, 1)).reshape(-1)
        normalized_block = (block - mean) / np.maximum(std, 1e-6)
        normalized.append(np.tile(normalized_block[None, :], (horizon, 1)))
    return raw, torch.as_tensor(np.stack(normalized), dtype=torch.float32)


class _Preprocessor(BasePolicy):
    def __init__(self, action_normalizer: ActionNormalizer):
        super().__init__()
        self.process = {"action": action_normalizer}
        self.transform = {"pixels": _image_transform(), "goal": _image_transform()}


def _rankdata(values: np.ndarray) -> np.ndarray:
    order = np.argsort(values, kind="stable")
    ranks = np.empty(len(values), dtype=np.float64)
    ranks[order] = np.arange(len(values), dtype=np.float64)
    return ranks


def _spearman(left: np.ndarray, right: np.ndarray) -> float:
    a = _rankdata(left)
    b = _rankdata(right)
    if np.std(a) < 1e-12 or np.std(b) < 1e-12:
        return 0.0
    return float(np.corrcoef(a, b)[0, 1])


def _rollout_candidate(
    env: gym.Env,
    seed: int,
    action: tuple[float, float] | np.ndarray,
    steps: int,
    action_block: int = 5,
) -> tuple[float, int]:
    env.reset(seed=int(seed))
    sequence = np.asarray(action, dtype=np.float32)
    if sequence.ndim == 1:
        sequence = sequence.reshape(1, -1)
    if sequence.ndim != 2 or sequence.shape[1] != 2:
        raise ValueError(f"candidate action must have shape [T,2], got {sequence.shape}")
    final_info = {}
    terminated = truncated = False
    for step in range(steps):
        macro_index = min(step // max(int(action_block), 1), len(sequence) - 1)
        _, _, terminated, truncated, final_info = env.step(sequence[macro_index])
        if terminated or truncated:
            break
    distance = float(np.asarray(final_info.get("distance_to_target", np.inf)).reshape(-1)[0])
    return distance, int(bool(terminated))


@torch.inference_mode()
def _model_rollout(
    model: torch.nn.Module,
    preprocessor: _Preprocessor,
    current: np.ndarray,
    goal: np.ndarray,
    action_normalizer: ActionNormalizer,
    candidates: torch.Tensor,
    device: str,
    history_len: int,
    *,
    return_goal: bool = False,
) -> np.ndarray:
    del action_normalizer
    if history_len <= 0:
        raise ValueError("history_len must be positive")
    # Match the live WorldModelPolicy input contract.  The current TwoRoom
    # runner supplies a single current frame/action (shape [B,1,...]); it does
    # not construct a three-frame stack.  Artificially repeating frames here
    # changes both the predictor input distribution and its effective horizon.
    raw = {
        "pixels": np.repeat(current[None, None], history_len, axis=1),
        # Goal is one RGB frame.  Keep only (environment, time) leading
        # dimensions; the preprocessor adds channel-first layout itself.
        "goal": goal[None, None],
        "action": np.zeros((1, history_len, 2), dtype=np.float32),
    }
    prepared = preprocessor._prepare_info(raw)
    model_info = {}
    bank_size = int(candidates.shape[0])
    for key in ("pixels", "goal", "action"):
        value = prepared[key].to(device)
        model_info[key] = value[:, None].expand(1, bank_size, *value.shape[1:]).contiguous()
    candidate_tensor = candidates.to(device).unsqueeze(0)
    cost = model.get_cost(model_info, candidate_tensor).squeeze(0).detach().cpu().numpy()
    source = model_info["emb"][0, :, -1].detach().cpu().numpy()
    predicted = model_info["predicted_emb"][0, :, -1].detach().cpu().numpy()
    goal_emb = model_info["goal_emb"]
    if goal_emb.ndim == 4:
        goal = goal_emb[0, :, -1].detach().cpu().numpy()
    elif goal_emb.ndim == 3:
        goal = goal_emb[0, -1].detach().cpu().numpy()[None, :]
        goal = np.repeat(goal, bank_size, axis=0)
    else:
        raise RuntimeError(f"unexpected goal embedding shape: {tuple(goal_emb.shape)}")
    result = (cost, source, predicted)
    return result + (goal,) if return_goal else result


def _model_costs(
    model: torch.nn.Module,
    preprocessor: _Preprocessor,
    current: np.ndarray,
    goal: np.ndarray,
    action_normalizer: ActionNormalizer,
    candidates: torch.Tensor,
    device: str,
    history_len: int,
) -> np.ndarray:
    """Backward-compatible scalar-cost wrapper used by ranking audits."""
    return _model_rollout(
        model, preprocessor, current, goal, action_normalizer, candidates, device, history_len
    )[0]


def _split_for_root(index: int, total: int) -> str:
    train_end = max(1, total // 2)
    calibration_end = train_end + max(1, (total - train_end) // 2)
    if index < train_end:
        return "train"
    if index < calibration_end:
        return "calibration"
    return "outcome"


def _write_candidate_panel(
    output: Path,
    *,
    args: argparse.Namespace,
    raw_bank: list[tuple[float, float]],
    panel_rows: list[dict],
    predicted_latents: dict[str, np.ndarray],
) -> None:
    """Write a provenance-complete offline panel for train-only diagnostics."""
    output.mkdir(parents=True, exist_ok=True)
    arrays_path = output / "arrays.npz"
    np.savez_compressed(
        arrays_path,
        **{f"predicted::{key}": value for key, value in predicted_latents.items()},
    )
    bank_hash = hashlib.sha256(
        np.asarray(raw_bank, dtype=np.float64).round(8).tobytes()
    ).hexdigest()[:20]
    for row in panel_rows:
        row["candidate_bank_hash"] = bank_hash
    metadata = {
        "schema": "gdd_wm_live_candidate_panel.v0.2",
        "environment": "TwoRoom",
        "candidate_bank_hash": bank_hash,
        "candidate_bank_coordinate_frame": "raw_control",
        "candidate_bank_count": len(raw_bank),
        "history_len": int(args.history_len),
        "replay_steps": int(args.replay_steps),
        "root_split": "first_half_train, second_half_evenly_split_calibration_outcome",
        "source_panel": "frozen RGB LeWM candidate ranking with simulator labels only",
        "panel_state_fields": "evaluator-side source_state_raw and goal_raw; never passed to model ranking",
        "runtime_teacher_forbidden": True,
        "outcome_used_for_teacher_or_metric_selection": False,
        "claim_boundary": (
            "TwoRoom offline candidate panel for train-only latent readout diagnostics; "
            "not D-JEPA teacher, causal physics, or closed-loop planning evidence."
        ),
    }
    dataset = {"metadata": metadata, "records": panel_rows}
    dataset_path = output / "candidate_dataset.json"
    dataset_path.write_text(json.dumps(dataset, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    manifest = {
        "schema": "gdd_wm_live_candidate_panel_manifest.v0.2",
        "candidate_dataset": str(dataset_path.resolve()),
        "arrays": str(arrays_path.resolve()),
        "record_count": len(panel_rows),
        "root_count": len({row["instance_id"] for row in panel_rows}),
        "split_root_counts": {
            split: len({row["instance_id"] for row in panel_rows if row["split"] == split})
            for split in ("train", "calibration", "outcome")
        },
        "claim_boundary": metadata["claim_boundary"],
    }
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy", default="/home/gbk/.stable_worldmodel/checkpoints/tworoom/lewm")
    parser.add_argument("--adapter-artifact", type=Path, default=Path("results/live_cross_environment_prediction_20261015/tworoom_cuda/cross_environment_prediction.json"))
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--seed", type=int, default=20261070)
    parser.add_argument("--roots", type=int, default=16)
    parser.add_argument("--replay-steps", type=int, default=25)
    parser.add_argument(
        "--history-len", type=int, default=1,
        help="live policy history length; TwoRoom runtime currently uses one frame",
    )
    parser.add_argument(
        "--panel-output", type=Path, default=None,
        help="optional directory for source/predicted latent plus outcome candidate panel",
    )
    args = parser.parse_args()
    if args.device.startswith("cuda") and not torch.cuda.is_available():
        raise RuntimeError("CUDA requested but unavailable")
    action_mean, action_std = _load_action_stats(args.adapter_artifact, "swm/TwoRoom-v1")
    action_normalizer = ActionNormalizer(action_mean, action_std)
    raw_bank, normalized_bank = _candidate_bank(action_mean, action_std)
    model = load_compatible_pretrained(args.policy, device=args.device).eval()
    model.requires_grad_(False)
    model.interpolate_pos_encoding = True
    preprocessor = _Preprocessor(action_normalizer)
    env = TwoRoomGoalAliasWrapper(gym.make("swm/TwoRoom-v1", render_mode="rgb_array"))
    rows = []
    panel_rows: list[dict] = []
    predicted_latents: dict[str, np.ndarray] = {}
    try:
        for root_index in range(args.roots):
            seed = int(args.seed + root_index)
            _, info = env.reset(seed=seed)
            current = np.asarray(env.render(), dtype=np.uint8).copy()
            goal = np.asarray(info["goal"], dtype=np.uint8).copy()
            model_cost, source_latents, predicted_terminal_latents, goal_latents = _model_rollout(
                model, preprocessor, current, goal, action_normalizer,
                normalized_bank, args.device, args.history_len, return_goal=True,
            )
            true_cost = np.asarray([
                _rollout_candidate(env, seed, action, args.replay_steps)[0]
                for action in raw_bank
            ], dtype=np.float64)
            predicted_best = int(np.argmin(model_cost))
            true_order = np.argsort(true_cost, kind="stable")
            true_rank = int(np.flatnonzero(true_order == predicted_best)[0] + 1)
            rows.append({
                "seed": seed,
                "predicted_best": predicted_best,
                "true_best": int(true_order[0]),
                "true_rank_of_predicted_best": true_rank,
                "top1_hit": int(predicted_best == int(true_order[0])),
                "top4_hit": int(predicted_best in set(true_order[:4].tolist())),
                "regret": float(true_cost[predicted_best] - true_cost[true_order[0]]),
                "spearman": _spearman(model_cost, true_cost),
                "model_cost": model_cost.tolist(),
                "true_cost": true_cost.tolist(),
            })
            if args.panel_output is not None:
                split = _split_for_root(root_index, args.roots)
                instance_id = f"tworoom_episode_{seed}"
                for candidate_index, action in enumerate(raw_bank):
                    record_key = f"{instance_id}/{candidate_index:03d}"
                    sequence = np.tile(
                        np.asarray(action, dtype=np.float32)[None, :],
                        (args.replay_steps, 1),
                    )
                    predicted_latents[record_key] = np.asarray(
                        predicted_terminal_latents[candidate_index], dtype=np.float32
                    )
                    panel_rows.append({
                        "instance_id": instance_id,
                        "split": split,
                        "environment": "TwoRoom",
                        "start_episode_id": str(seed),
                        "candidate_id": f"candidate_{candidate_index:03d}",
                        "candidate_bank_hash": "pending_written_by_panel_writer",
                        "action_sequence": sequence.tolist(),
                        "total_action_steps": int(args.replay_steps),
                        "candidate_generator": "tworoom_shared_directions_v1",
                        "cem_stage": "fixed_counterfactual_bank",
                        "source_observation_ref": f"live_rgb://TwoRoom/{seed}/current",
                        "goal_observation_ref": f"live_rgb://TwoRoom/{seed}/goal",
                        "source_state_raw": np.asarray(info["state"], dtype=np.float64).tolist(),
                        "goal_raw": np.asarray(info["goal_state"], dtype=np.float64).tolist(),
                        "teacher_model_id": "frozen_lewm_cost_v1",
                        "teacher_score": float(-model_cost[candidate_index]),
                        "teacher_rank": int(np.flatnonzero(np.argsort(model_cost) == candidate_index)[0]),
                        "teacher_set_id": f"{instance_id}_shared_bank",
                        "real_success": None,
                        "real_task_cost": float(true_cost[candidate_index]),
                        "realized_observation_ref": f"offline_mujoco_state://{record_key}",
                        "predicted_latent_ref": f"arrays.npz::predicted::{record_key}",
                        "realized_latent_ref": None,
                        "action_support": {
                            "chart": "raw_control",
                            "min": float(np.min(sequence)),
                            "max": float(np.max(sequence)),
                            "duration_steps": int(args.replay_steps),
                        },
                        "privileged_state_role": "offline_outcome_label_only",
                        "source_latent_model": np.asarray(
                            source_latents[candidate_index], dtype=np.float64
                        ).tolist(),
                        "goal_latent_model": np.asarray(
                            goal_latents[candidate_index], dtype=np.float64
                        ).tolist(),
                        "predicted_horizon": 5,
                    })
    finally:
        env.close()
    if args.panel_output is not None:
        _write_candidate_panel(
            args.panel_output,
            args=args,
            raw_bank=raw_bank,
            panel_rows=panel_rows,
            predicted_latents=predicted_latents,
        )
    top1 = np.asarray([row["top1_hit"] for row in rows], dtype=np.float64)
    top4 = np.asarray([row["top4_hit"] for row in rows], dtype=np.float64)
    ranks = np.asarray([row["true_rank_of_predicted_best"] for row in rows], dtype=np.float64)
    regrets = np.asarray([row["regret"] for row in rows], dtype=np.float64)
    spearman = np.asarray([row["spearman"] for row in rows], dtype=np.float64)
    payload = {
        "schema": "tworoom_shared_candidate_ranking.v1",
        "protocol": {
            "roots": "seed-disjoint root replay",
            "candidate_bank": "zero, axis-aligned magnitudes 0.25/0.50/0.75, and four diagonals",
            "candidate_count": len(raw_bank),
            "replay_steps": int(args.replay_steps),
            "model_input": "RGB current frame and RGB goal only, with live history length",
            "history_len": int(args.history_len),
            "simulator_use": "held-out labels only; never passed to model ranking",
            "checkpoint_frozen": True,
            "device": args.device,
            "panel_output": str(args.panel_output.resolve()) if args.panel_output is not None else None,
        },
        "roots": rows,
        "summary": {
            "n": int(len(rows)),
            "top1_accuracy": float(top1.mean()),
            "top4_accuracy": float(top4.mean()),
            "mean_true_rank_of_predicted_best": float(ranks.mean()),
            "mean_regret": float(regrets.mean()),
            "median_regret": float(np.median(regrets)),
            "mean_spearman": float(spearman.mean()),
        },
        "claim_boundary": "Shared-candidate RGB ranking diagnostic with privileged offline labels; not online planning or a universal transfer certificate.",
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(payload["summary"], indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
