"""Evaluate functional consequences of equivariance interventions.

This companion benchmark reuses the exact training and checkpoint-selection
path from ``run_predictor_equivariance_synthetic.py`` and changes only the
evaluation distribution.  It measures action-magnitude OOD, shifted initial
states, combined OOD, multi-step rollout, and a controlled candidate-set
latent-planning proxy.

The planning metric is deliberately not an environment success rate: a goal is
generated by one candidate action sequence, and the learned model selects
among the same candidate set by predicted latent goal distance.  Physical goal
distance and agreement with the oracle candidate are reported separately.
The artifact is synthetic vector-world evidence, not LeWM, PushT, online
planning, causal controllability, or GPU evidence.
"""

