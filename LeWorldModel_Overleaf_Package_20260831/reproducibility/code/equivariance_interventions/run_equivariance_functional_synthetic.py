@dataclass(frozen=True)
class FunctionalBenchmarkConfig:
    train_epochs: int = 120
    train_samples: int = 512
    validation_samples: int = 256
    test_samples: int = 512
    rollout_trajectories: int = 256
    rollout_horizon: int = 8
    ood_action_scale: float = 0.50
    ood_state_shift: float = 2.0
    planning_tasks: int = 96
    planning_candidates: int = 64
    planning_horizon: int = 4
    planning_success_threshold: float = 0.25


def _make_one_step_split(
    count: int,
    state_dim: int,
    generator: torch.Generator,
    *,
    action_scale: float = 0.25,
    state_shift: float = 0.0,
) -> dict[str, torch.Tensor]:
    state = torch.randn(count, state_dim, generator=generator) + state_shift
    action = action_scale * torch.randn(count, state_dim, generator=generator)
    return {"state": state, "action": action, "target": state + action}


def _make_rollout_split(
    count: int,
    state_dim: int,
    horizon: int,
    generator: torch.Generator,
    *,
    action_scale: float = 0.25,
    state_shift: float = 0.0,
) -> dict[str, torch.Tensor]:
    base = torch.randn(count, state_dim, generator=generator) + state_shift
    actions = action_scale * torch.randn(
        count, horizon, state_dim, generator=generator
    )
    cumulative = torch.zeros_like(base)
    states = [base]
    for step in range(horizon):
        cumulative = cumulative + actions[:, step]
        states.append(base + cumulative)
    return {"states": torch.stack(states, dim=1), "actions": actions}


@torch.no_grad()
def _one_step_mse(model, split: dict[str, torch.Tensor]) -> float:
    source = model.encode(split["state"])
    target = model.encode(split["target"])
    prediction = model.predict(source, split["action"])
    return float((prediction - target).square().mean())


@torch.no_grad()
def _rollout_mse(
    model,
    split: dict[str, torch.Tensor],
    horizons: tuple[int, ...],
) -> dict[str, float]:
    states = split["states"]
    actions = split["actions"]
    truth = model.encode(states.reshape(-1, states.size(-1))).reshape(
        states.size(0), states.size(1), -1
    )
    current = truth[:, 0]
    output: dict[str, float] = {}
    for step in range(actions.size(1)):
        current = model.predict(current, actions[:, step])
        if step + 1 in horizons:
            output[str(step + 1)] = float(
                (current - truth[:, step + 1]).square().mean()
            )
    return output


@torch.no_grad()
def _composition_error(model, base: torch.Tensor, action_scale: float) -> float:
    generator = torch.Generator().manual_seed(1701 + int(action_scale * 1000))
    first = action_scale * torch.randn(
        base.size(0), base.size(1), generator=generator
    )
    second = action_scale * torch.randn(
        base.size(0), base.size(1), generator=generator
    )
    initial = model.encode(base)
    composed = model.predict(model.predict(initial, first), second)
    target = model.encode(base + first + second)
    denominator = target.square().mean().sqrt().clamp_min(1e-8)
    return float((composed - target).square().mean().sqrt() / denominator)


@torch.no_grad()
def _planning_proxy(
    model,
    config: FunctionalBenchmarkConfig,
    generator: torch.Generator,
    *,
    action_scale: float,
    state_shift: float,
) -> dict[str, float]:
    """Select a candidate by latent goal distance and score it in state space."""

    state_dim = 4
    states = torch.randn(config.planning_tasks, state_dim, generator=generator)
    states = states + state_shift
    actions = action_scale * torch.randn(
        config.planning_tasks,
        config.planning_candidates,
        config.planning_horizon,
        state_dim,
        generator=generator,
    )
    goals = states + actions[:, 0].sum(dim=1)
    true_finals = states[:, None, :] + actions.sum(dim=2)
    physical_distances = (true_finals - goals[:, None, :]).norm(dim=-1)
    oracle_index = physical_distances.argmin(dim=1)
    oracle_distance = physical_distances.gather(1, oracle_index[:, None]).squeeze(1)

    start_latent = model.encode(states)
    goal_latent = model.encode(goals)
    current = start_latent[:, None, :].expand(
        -1, config.planning_candidates, -1
    ).reshape(-1, start_latent.size(-1))
    for step in range(config.planning_horizon):
        current = model.predict(
            current,
            actions[:, :, step, :].reshape(-1, state_dim),
        )
    predicted_final = current.reshape(
        config.planning_tasks, config.planning_candidates, -1
    )
    latent_goal_loss = (predicted_final - goal_latent[:, None, :]).square().mean(dim=-1)
    selected_index = latent_goal_loss.argmin(dim=1)
    selected_distance = physical_distances.gather(1, selected_index[:, None]).squeeze(1)
    return {
        "selected_goal_distance": float(selected_distance.mean()),
        "oracle_goal_distance": float(oracle_distance.mean()),
        "planning_regret": float((selected_distance - oracle_distance).mean()),
        "goal_success_rate": float(
            (selected_distance <= config.planning_success_threshold).float().mean()
        ),
        "oracle_success_rate": float(
            (oracle_distance <= config.planning_success_threshold).float().mean()
        ),
        "oracle_choice_agreement": float((selected_index == oracle_index).float().mean()),
    }


def _finite(value: object) -> bool:
    if isinstance(value, dict):
        return all(_finite(item) for item in value.values())
    if isinstance(value, (float, int)):
        return math.isfinite(float(value))
    return True


def _evaluate_one(
    mode: str,
    weight: float,
    seed: int,
    config: FunctionalBenchmarkConfig,
) -> dict[str, object]:
    train_config = EquivarianceBenchmarkConfig(
        train_samples=config.train_samples,
        validation_samples=config.validation_samples,
        test_samples=config.test_samples,
        rollout_trajectories=config.rollout_trajectories,
        rollout_horizon=config.rollout_horizon,
        epochs=config.train_epochs,
    )
    bundle: TrainedBenchmark = _fit_model(mode, weight, seed, train_config)
    model = bundle.model
    state_dim = train_config.state_dim
    generator = torch.Generator().manual_seed(10000 + seed)
    splits = {
        "action_2x": _make_one_step_split(
            config.test_samples,
            state_dim,
            generator,
            action_scale=config.ood_action_scale,
        ),
        "state_shift": _make_one_step_split(
            config.test_samples,
            state_dim,
            generator,
            state_shift=config.ood_state_shift,
        ),
        "combined": _make_one_step_split(
            config.test_samples,
            state_dim,
            generator,
            action_scale=config.ood_action_scale,
            state_shift=config.ood_state_shift,
        ),
    }
    rollout_splits = {
        "action_2x": _make_rollout_split(
            config.rollout_trajectories,
            state_dim,
            config.rollout_horizon,
            generator,
            action_scale=config.ood_action_scale,
        ),
        "state_shift": _make_rollout_split(
            config.rollout_trajectories,
            state_dim,
            config.rollout_horizon,
            generator,
            state_shift=config.ood_state_shift,
        ),
        "combined": _make_rollout_split(
            config.rollout_trajectories,
            state_dim,
            config.rollout_horizon,
            generator,
            action_scale=config.ood_action_scale,
            state_shift=config.ood_state_shift,
        ),
    }
    test_base = bundle.test["state"]
    planning_id = _planning_proxy(
        model,
        config,
        generator,
        action_scale=0.25,
        state_shift=0.0,
    )
    planning_ood = _planning_proxy(
        model,
        config,
        generator,
        action_scale=config.ood_action_scale,
        state_shift=config.ood_state_shift,
    )
    record: dict[str, object] = {
        "mode": mode,
        "regularization_weight": weight,
        "seed": seed,
        "device": "cpu",
        "train_best_epoch": bundle.best_epoch,
        "train_one_step_mse": _one_step_mse(model, bundle.test),
        "ood_one_step_mse": {
            key: _one_step_mse(model, split) for key, split in splits.items()
        },
        "ood_rollout_mse": {
            key: _rollout_mse(model, split, (1, 4, 8))
            for key, split in rollout_splits.items()
        },
        "composition_error": {
            "in_distribution": _composition_error(model, test_base, 0.25),
            "ood_action": _composition_error(
                model, test_base, config.ood_action_scale
            ),
        },
        "planning": {
            "in_distribution": planning_id,
            "ood_combined": planning_ood,
        },
        "protocol": {
            "transition": "s_next = s + a",
            "train_action_scale": 0.25,
            "ood_action_scale": config.ood_action_scale,
            "ood_state_shift": config.ood_state_shift,
            "planning_success_threshold": config.planning_success_threshold,
        },
    }
    if not _finite(record):
        raise FloatingPointError(f"non-finite functional record: {mode}:{seed}")
    return record


def _summary(records: list[dict[str, object]]) -> dict[str, object]:
    paths = {
        "train_one_step_mse": lambda r: r["train_one_step_mse"],
        "ood_action_one_step_mse": lambda r: r["ood_one_step_mse"]["action_2x"],
        "ood_combined_one_step_mse": lambda r: r["ood_one_step_mse"]["combined"],
        "ood_action_rollout_h8_mse": lambda r: r["ood_rollout_mse"]["action_2x"]["8"],
        "ood_combined_rollout_h8_mse": lambda r: r["ood_rollout_mse"]["combined"]["8"],
        "in_distribution_planning_success": lambda r: r["planning"]["in_distribution"]["goal_success_rate"],
        "ood_planning_success": lambda r: r["planning"]["ood_combined"]["goal_success_rate"],
        "in_distribution_planning_regret": lambda r: r["planning"]["in_distribution"]["planning_regret"],
        "ood_planning_regret": lambda r: r["planning"]["ood_combined"]["planning_regret"],
    }
    grouped: dict[str, list[dict[str, object]]] = {}
    for record in records:
        grouped.setdefault(f"{record['mode']}:{record['regularization_weight']}", []).append(record)

    def mean_std(values: list[float]) -> dict[str, float]:
        mean = sum(values) / len(values)
        std = 0.0 if len(values) < 2 else math.sqrt(
            sum((value - mean) ** 2 for value in values) / (len(values) - 1)
        )
        return {"mean": mean, "std": std}

    output: dict[str, object] = {}
    for key, rows in grouped.items():
        output[key] = {
            metric: mean_std([float(extractor(row)) for row in rows])
            for metric, extractor in paths.items()
        }
        output[key]["n_seeds"] = len(rows)  # type: ignore[index]
    return output


def _write_markdown(report: dict[str, object], output: Path) -> None:
    lines = [
        "# Functional consequences of equivariance interventions",
        "",
        "This is a controlled synthetic vector-world benchmark, not a LeWM, PushT, online-planning, causal-control, or GPU result.",
        "The training checkpoint and loss are shared with the predictor-equivariance ablation; only the evaluation distribution changes.",
        "",
        "| mode | weight | ID one-step MSE | OOD action MSE | OOD combined h=8 MSE | ID planning success | OOD planning success | ID regret | OOD regret |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for key, values in report["summary"].items():
        mode, weight = key.split(":", 1)
        def fmt(metric: str) -> str:
            value = values[metric]
            return f"{value['mean']:.6g} +/- {value['std']:.2g}"
        lines.append(
            f"| {mode} | {float(weight):.6g} | {fmt('train_one_step_mse')} | "
            f"{fmt('ood_action_one_step_mse')} | {fmt('ood_combined_rollout_h8_mse')} | "
            f"{fmt('in_distribution_planning_success')} | {fmt('ood_planning_success')} | "
            f"{fmt('in_distribution_planning_regret')} | {fmt('ood_planning_regret')} |"
        )
    lines.extend(
        [
            "",
            "The planning columns are controlled candidate-set metrics: a goal is generated by one candidate action sequence, the model selects by predicted latent goal distance, and the selected physical goal distance is evaluated against the oracle candidate set.",
            "",
            "Interpretation boundary: this benchmark tests whether geometry changes transfer under controlled OOD and candidate-set planning probes. It does not establish online task success, PushT performance, causal controllability, or a universal relation between equivariance error and planning.",
        ]
    )
    output.write_text("\n".join(lines) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--epochs", type=int, default=120)
    parser.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    parser.add_argument("--weights", type=float, nargs="+", default=[1.0, 10.0])
    args = parser.parse_args()
    config = FunctionalBenchmarkConfig(train_epochs=args.epochs)
    modes = ["none", "latent", "predictor", "both"]
    records: list[dict[str, object]] = []
    start = time.time()
    for mode in modes:
        weights = [0.0] if mode == "none" else args.weights
        for weight in weights:
            for seed in args.seeds:
                print(
                    f"[functional-benchmark] mode={mode} weight={weight} seed={seed}: "
                    "measuring OOD rollout and candidate-set planning"
                )
                records.append(_evaluate_one(mode, weight, seed, config))
    report = {
        "protocol": {
            **asdict(config),
            "modes": modes,
            "weights": args.weights,
            "seeds": args.seeds,
            "synthetic_vector_world_only": True,
            "elapsed_seconds": time.time() - start,
        },
        "records": records,
        "summary": _summary(records),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n")
    _write_markdown(report, args.output.with_suffix(".md"))
    print(json.dumps(report["summary"], indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
